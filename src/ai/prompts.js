// 把上传文档的上下文注入到最后一条 user 消息（若无 user 消息则作为 system 前缀）
export function injectContext(messages, context) {
  if (!context || !context.trim()) return messages
  const msgs = messages.map((m) => ({ ...m }))
  let idx = -1
  for (let i = msgs.length - 1; i >= 0; i--) {
    if (msgs[i].role === 'user') {
      idx = i
      break
    }
  }
  if (idx >= 0) {
    msgs[idx].content = context + '\n\n' + msgs[idx].content
  } else {
    msgs.unshift({ role: 'system', content: context })
  }
  return msgs
}

